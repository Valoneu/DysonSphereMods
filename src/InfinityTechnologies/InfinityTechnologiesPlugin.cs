        [HarmonyPostfix]
        [HarmonyPatch(typeof(Mecha), "GenerateEnergy")]
        public static void Mecha_GenerateEnergy_Postfix(Mecha __instance, double dt, double __state)
        {
            if (FuelEfficiencyMultiplier > 1.001f)
            {
                double consumed = __state - __instance.reactorEnergy;
                if (consumed > 0.0001)
                {
                    // Give back reactor energy so the fuel rod lasts longer
                    __instance.reactorEnergy += consumed * (1.0 - 1.0 / FuelEfficiencyMultiplier);

                    // Add extra core energy from the increased yield
                    double extraCore = consumed * (FuelEfficiencyMultiplier - 1.0);
                    lock (__instance)
                    {
                        __instance.coreEnergy += extraCore;
                        if (__instance.coreEnergy > __instance.coreEnergyCap)
                            __instance.coreEnergy = __instance.coreEnergyCap;
                        __instance.MarkEnergyChange(1, extraCore);
                    }
                }
            }
        }

        // ============================================================================
        //  PATCH: Wireless Power — boost the mecha charge from wireless towers
        // ============================================================================
        [HarmonyPrefix]
        [HarmonyPatch(typeof(Mecha), nameof(Mecha.MarkEnergyChange))]
        public static void Mecha_MarkEnergyChange_Prefix(Mecha __instance, int func, ref double change)
        {
            if (func == 2 && WirelessPowerMultiplier > 1.001f)
            {
                double originalChange = change;
                change *= WirelessPowerMultiplier; // Boost the statistical change
                
                // Boost the REAL energy
                double extra = change - originalChange;
                __instance.coreEnergy += extra;
                if (__instance.coreEnergy > __instance.coreEnergyCap)
                    __instance.coreEnergy = __instance.coreEnergyCap;
            }
        }

