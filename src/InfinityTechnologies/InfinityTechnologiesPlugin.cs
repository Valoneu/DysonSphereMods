        // ============================================================================
        //  Core modifier calculation from tech levels
        // ============================================================================
        public static void RecalculateModifiers()
        {
            var history = GameMain.history;
            if (history == null || LDB.techs == null) return;

            SpherePowerMultiplier = 1f;
            ProliferatorMultiplier = 1f;
            FuelEfficiencyMultiplier = 1f;
            CombatSpeedMultiplier = 1f;
            RayReceiverMultiplier = 1f;
            AccumulatorMultiplier = 1f;
            WirelessPowerMultiplier = 1f;
            ResearchProductivityMultiplier = 1f;
            AutoRepairBonus = 0;

            // Helper: given a tech ID and per-level bonus, compute 1 + levels * bonus
            float CalcMultiplier(int techId, float perLevel)
            {
                if (history.techStates.TryGetValue(techId, out var state))
                {
                    var proto = LDB.techs.Select(techId);
                    if (proto != null)
                    {
                        int levels = Math.Max(0, state.curLevel - proto.Level);
                        return 1f + levels * perLevel;
                    }
                }
                return 1f;
            }

            int CalcLevels(int techId)
            {
                if (history.techStates.TryGetValue(techId, out var state))
                {
                    var proto = LDB.techs.Select(techId);
                    if (proto != null)
                        return Math.Max(0, state.curLevel - proto.Level);
                }
                return 0;
            }

            WirelessPowerMultiplier = CalcMultiplier(9002, 0.2f);
            RayReceiverMultiplier = CalcMultiplier(9003, 0.1f);
            AccumulatorMultiplier = CalcMultiplier(9004, 0.2f);
            SpherePowerMultiplier = CalcMultiplier(9051, 0.01f);
            ProliferatorMultiplier = CalcMultiplier(9052, 0.0025f);
            FuelEfficiencyMultiplier = CalcMultiplier(9053, 0.02f);
            CombatSpeedMultiplier = CalcMultiplier(9054, 0.05f);
            ResearchProductivityMultiplier = CalcMultiplier(9055, 0.1f);
            AutoRepairBonus = CalcLevels(9005);

            // Update Dyson Sphere power output
            if (GameMain.data != null && GameMain.data.dysonSpheres != null)
            {
                foreach (var ds in GameMain.data.dysonSpheres)
                {
                    if (ds == null) continue;
                    UpdateDysonSpherePower(ds);
                }
            }

            // Proliferator table modifications
            if (ProliferatorMultiplier > 1.0001f)
            {
                for (int i = 1; i <= 10; i++)
                {
                    if (i == 1 || i == 2 || i == 4)
                    {
                        double baseInc = i == 1 ? 0.125 : (i == 2 ? 0.2 : 0.25);
                        Cargo.incTableMilli[i] = Math.Min(0.5, baseInc * ProliferatorMultiplier);
                        Cargo.accTableMilli[i] = Math.Min(2.5, (double)Cargo.accTable[i] / 1000.0 * ProliferatorMultiplier);
                    }
                }
            }
        }

        public static void UpdateDysonSpherePower(DysonSphere ds)
        {
            if (ds == null || ds.starData == null || SpherePowerMultiplier <= 1.0001f) return;
            float lumino = ds.starData.dysonLumino;
            ds.energyGenPerSail = (long)(Configs.freeMode.solarSailEnergyPerTick * lumino * SpherePowerMultiplier);
            ds.energyGenPerNode = (long)(Configs.freeMode.dysonNodeEnergyPerTick * lumino * SpherePowerMultiplier);
            ds.energyGenPerFrame = (long)(Configs.freeMode.dysonFrameEnergyPerTick * lumino * SpherePowerMultiplier);
            ds.energyGenPerShell = (long)(Configs.freeMode.dysonShellEnergyPerTick * lumino * SpherePowerMultiplier);
            
            var field = typeof(DysonSphere).GetField("needRecalculatePower", BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance);
            if (field != null) field.SetValue(ds, true);
        }

