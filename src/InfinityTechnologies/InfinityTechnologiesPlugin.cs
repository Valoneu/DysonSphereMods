            long hashDelta = ts.hashUploaded - prevHash;
            long registerDelta = hashRegister - prevRegister;

            if (hashDelta > 0)
            {
                long bonusHash = (long)(hashDelta * (ResearchProductivityMultiplier - 1.0f));
                ts.hashUploaded += bonusHash;
                
                if (ts.hashUploaded > ts.hashNeeded)
                    ts.hashUploaded = ts.hashNeeded;
            }

            if (registerDelta > 0)
            {
                long bonusRegister = (long)(registerDelta * (ResearchProductivityMultiplier - 1.0f));
                hashRegister += bonusRegister;
            }
        }
    }
