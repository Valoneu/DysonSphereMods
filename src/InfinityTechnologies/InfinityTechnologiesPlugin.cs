        // ============================================================================
        //  PATCH: Tech Tree UI — display custom function text
        // ============================================================================
        [HarmonyPostfix]
        [HarmonyPatch(typeof(TechProto), nameof(TechProto.UnlockFunctionText))]
        public static void TechProto_UnlockFunctionText_Postfix(TechProto __instance, ref string __result, StringBuilder sb)
        {
            if (__instance.ID < 9000) return;

            List<string> lines = new List<string>();
            
            bool hasVanilla = false;
            foreach (int funcId in __instance.UnlockFunctions)
            {
                if (funcId < 100) hasVanilla = true;
            }

            for (int i = 0; i < __instance.UnlockFunctions.Length; i++)
            {
                int funcId = __instance.UnlockFunctions[i];
                if (funcId >= 100)
                {
                    string key = $"TechFunction_{funcId}";
                    string translatedFormat = key.Translate();
                    if (translatedFormat != key)
                    {
                        lines.Add(string.Format(translatedFormat, __instance.UnlockValues[i]));
                    }
                }
            }

            if (lines.Count > 0)
            {
                if (string.IsNullOrEmpty(__result) || !hasVanilla)
                    __result = string.Join("\r\n", lines);
                else
                    __result += "\r\n" + string.Join("\r\n", lines);
            }
        }

